import { FIXED_DT } from '../core/loop';

/**
 * 渲染这一帧该把轮子转到哪个角度。
 *
 * **轮子必须和车身一样插值,而且要按角速度外推、不能按角度插值。**
 *
 * 上一版这里写着「悬挂行程和转向角的变化幅度是厘米/几度的量级,插不插值
 * 看不出来」—— 对那两个是对的,**但滚转角不在这个量级里**:24 m/s 时每个
 * 物理步就转 66°。物理是固定 60 Hz 步进、渲染按 `alpha` 插值的,所以在
 * 120/144 Hz 的屏幕上,车身平滑地走、轮子却每两三帧才跳一次 —— 人类反馈的
 * 「模型一直在卡」里,轮子这一份就是这么来的。
 *
 * 按角度插值(lerp 到当前 `rollAngle`)不行:`rollAngle` 对 2π 取过模,
 * 跨越 0 的那一步会插成反方向的一大圈。按角速度回推没有这个问题,而且它
 * 就是物理积分本身用的量,插出来的中间值和物理完全一致。
 *
 * 注意这**治不了**高速下的频闪(轮辐每帧转过的角度接近轮辐的旋转对称周期,
 * 看起来像在倒转)—— 那是采样定理,只有运动模糊能解,见 `docs/HANDOFF.md`
 * 第四十七节。
 */
export function rollAt(wheel: { rollAngle: number; spin: number }, alpha: number): number {
  return wheel.rollAngle - wheel.spin * (1 - alpha) * FIXED_DT;
}
